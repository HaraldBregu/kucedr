// Third-party notices (roadmap 6.4): every package the app ships or compiles into a bundled plugin script.
// Usage: npm run notices
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const scripts = path.join(root, 'resources/plugins/bootstrap/scripts');
const stack = Object.keys(JSON.parse(readFileSync('package.json', 'utf8')).dependencies ?? {}).map((name) => [root, name]);
for (const script of readdirSync(scripts)) {
	const file = path.join(scripts, script, 'package.json');
	if (!existsSync(file)) continue;
	const { dependencies = {}, devDependencies = {} } = JSON.parse(readFileSync(file, 'utf8'));
	stack.push(...Object.keys({ ...dependencies, ...devDependencies }).map((name) => [path.join(scripts, script), name]));
}

const packages = new Map();
while (stack.length > 0) {
	const [from, name] = stack.pop();
	let dir = from;
	let found;
	while (!found) {
		const candidate = path.join(dir, 'node_modules', name);
		if (existsSync(path.join(candidate, 'package.json'))) found = candidate;
		else if (path.dirname(dir) === dir) break;
		else dir = path.dirname(dir);
	}
	if (!found || packages.has(found)) continue;
	const manifest = JSON.parse(readFileSync(path.join(found, 'package.json'), 'utf8'));
	const license =
		typeof manifest.license === 'string'
			? manifest.license
			: (manifest.license?.type ?? manifest.licenses?.map((item) => item.type).join(' OR ') ?? 'not stated');
	const text = readdirSync(found)
		.filter((file) => /^(licen[cs]e|copying|notice)/i.test(file))
		.sort()
		.map((file) => readFileSync(path.join(found, file), 'utf8').trim())
		.join('\n\n');
	packages.set(found, { id: `${manifest.name}@${manifest.version} (${license})`, text });
	stack.push(...Object.keys(manifest.dependencies ?? {}).map((dep) => [found, dep]));
}

const groups = new Map();
for (const { id, text } of packages.values()) groups.set(text, [...(groups.get(text) ?? []), id]);
const sections = [...groups]
	.map(([text, ids]) => [text, [...new Set(ids)].sort()])
	.sort((a, b) => a[1][0].localeCompare(b[1][0]))
	.map(([text, ids]) =>
		[`## ${ids.join(', ')}`, text ? `\`\`\`\`text\n${text}\n\`\`\`\`` : 'The package includes no license file.'].join('\n\n')
	);
writeFileSync(
	'THIRD_PARTY_NOTICES.md',
	[
		'# Third-party notices',
		'Kucedr includes the open-source packages below, in the app itself or compiled into its bundled plugin scripts. Electron and Chromium ship their own notices in the `LICENSE` and `LICENSES.chromium.html` files next to the app. This file is generated by `npm run notices`; do not edit it by hand.',
		...sections,
	].join('\n\n') + '\n'
);
console.log(`${packages.size} packages, ${groups.size} license texts`);
